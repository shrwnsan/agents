#!/usr/bin/env python3
"""Render a coverage-ledger JSONL file as the guide's markdown coverage table.

Reads one app's ledger (same format scripts/ledger-check.py validates) and
prints a markdown table: one row per audit round, one column per concern
class. Output is a build artifact — paste it between the generated-table
markers in the app's guide and never hand-edit it.

Usage:
  generate-coverage-table.py LEDGER.jsonl [--out PATH]
"""

import argparse
import json
import sys

CLASSES = [f"C{i}" for i in range(1, 10)]
GLYPH_EVIDENCE = "✓"
GLYPH_NA = "–"


def cell(v):
    if v == "evidence":
        return GLYPH_EVIDENCE
    if v == "n/a":
        return GLYPH_NA
    if isinstance(v, str) and v.startswith("carryover:"):
        return "⤺ " + v.split(":", 1)[1]
    return "?"


def jev_summary(jev):
    if not jev:
        return "—"
    wins = jev.get("windows") or []
    auto = sum(1 for w in wins if w.get("auto"))
    model = jev.get("model", "?")
    return f"{auto}/{len(wins)} auto · {model}"


def main():
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("ledger")
    ap.add_argument("--out")
    args = ap.parse_args()

    rows = []
    with open(args.ledger) as f:
        for line in f:
            line = line.strip()
            if line:
                rows.append(json.loads(line))
    rows.sort(key=lambda r: (r["round_date"], r["version"]))

    out = []
    out.append("<!-- GENERATED by scripts/generate-coverage-table.py — do not hand-edit -->")
    head = "| round | version | validation | " + " | ".join(CLASSES) + " | jev |"
    out.append(head)
    out.append("|" + "---|" * (3 + len(CLASSES) + 1))
    for r in rows:
        cov = r["coverage"]
        cells = " | ".join(cell(cov[c]) for c in CLASSES)
        val = r["validation"]
        out.append(f"| {r['round_date']} | {r['version']} | {val} | {cells} | {jev_summary(r.get('jev'))} |")
    out.append("")
    out.append("✓ evidence this round · ⤺ date = carried from that round · – not applicable. Validation: dual-run = independent reproducer, solo = single pass, carryover = no new binary.")

    text = "\n".join(out) + "\n"
    if args.out:
        with open(args.out, "w") as f:
            f.write(text)
        print(f"wrote {args.out}")
    else:
        sys.stdout.write(text)


if __name__ == "__main__":
    main()
